import { chromium } from 'playwright';
const port = process.argv[2]; const base = `http://127.0.0.1:${port}`;
await fetch(base + '/__reset', { method: 'POST' });
const b = await chromium.launch(); const ctx = await b.newContext({ viewport:{width:1440,height:900}, locale:'en-US', timezoneId:'UTC' }); const p = await ctx.newPage();
await p.goto(base + '/'); await p.waitForLoadState('networkidle');
const r = {}; const c = async (k, loc) => { r[k] = await loc.filter({visible:true}).count(); };
await c('button "Take a note"', p.getByRole('button', { name: 'Take a note', exact: true }));
await p.getByRole('button', { name: 'Take a note', exact: true }).click();
const d = p.getByRole('dialog', { name: 'Note editor', exact: true });
await c('dialog "Note editor"', d);
await c('textbox "Title"', d.getByRole('textbox', { name: 'Title', exact: true }));
await c('textbox "Content"', d.getByRole('textbox', { name: 'Content', exact: true }));
await c('button "Close"', d.getByRole('button', { name: 'Close', exact: true }));
await d.getByRole('textbox', { name: 'Title', exact: true }).fill('Study schedule s0');
await d.getByRole('textbox', { name: 'Content', exact: true }).fill('x');
await d.getByRole('button', { name: 'Close', exact: true }).click(); await p.waitForTimeout(500);
await c('region "{title}"', p.getByRole('region', { name: 'Study schedule s0', exact: true }));
await c('searchbox "Search"', p.getByRole('searchbox', { name: 'Search', exact: true }));
await p.getByRole('searchbox', { name: 'Search', exact: true }).fill('st'); await p.waitForTimeout(400);
await c('region "Highlight st" in note', p.getByRole('region', { name: 'Study schedule s0', exact: true }).getByRole('region', { name: 'Highlight st', exact: true }));
await p.getByRole('searchbox', { name: 'Search', exact: true }).fill(''); 
await p.getByRole('searchbox', { name: 'Search', exact: true }).blur(); await p.getByRole('searchbox', { name: 'Search', exact: true }).focus(); await p.waitForTimeout(400);
const sf = p.getByRole('region', { name: 'Suggested filters', exact: true });
await c('region "Suggested filters"', sf);
await c('button "Reminders" in Suggested filters', sf.getByRole('button', { name: 'Reminders', exact: true }));
await c('button "Notes" (Sidebar)', p.getByRole('navigation', { name: 'Sidebar' }).getByRole('button', { name: 'Notes', exact: true }));
console.log(JSON.stringify(r)); await b.close();
